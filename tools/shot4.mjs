import { createRequire } from "module";
const require = createRequire(process.env.HOME + "/development/pixel-arcade/tools/package.json");
const { chromium } = require("playwright");
const out = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("http://localhost:8791/app/");
await page.evaluate(() => localStorage.clear());
await page.goto("http://localhost:8791/app/#/m/w08/learn");
await page.waitForSelector(".cell.active");
await page.click('.toc[data-i="3"]');
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/30-group1.png` });
await page.keyboard.press("Space"); await page.keyboard.press("Space");
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/31-group3.png` });
for (let k = 0; k < 4; k++) await page.keyboard.press("Space");
await page.keyboard.press("b");
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/32-done-bulb.png` });
console.log("errors", JSON.stringify(errors));
await browser.close();
