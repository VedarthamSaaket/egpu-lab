import { createRequire } from "module";
const require = createRequire(process.env.HOME + "/development/pixel-arcade/tools/package.json");
const { chromium } = require("playwright");
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("http://localhost:8791/app/");
await page.evaluate(() => localStorage.clear());
await page.goto("http://localhost:8791/app/#/m/w02/learn");
await page.waitForSelector(".cell.active");
for (let k = 0; k < 12; k++) await page.keyboard.press("Space");
const before = await page.evaluate(() => [App.S.active, document.querySelectorAll(".toc.done").length]);
await page.click("[data-act=relearn]");
await page.waitForTimeout(300);
const after = await page.evaluate(() => [App.S.active, document.querySelectorAll(".toc.done").length, document.querySelectorAll(".cell.done").length]);
await page.screenshot({ path: process.argv[2] });
console.log("before", before, "after", after, "errors", JSON.stringify(errors));
await browser.close();
