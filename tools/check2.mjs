import { createRequire } from "module";
import fs from "fs";
const require = createRequire(process.env.HOME + "/development/pixel-arcade/tools/package.json");
const { chromium } = require("playwright");
const out = process.argv[2];
const base = "http://localhost:8791/app/";
const src = fs.readFileSync(process.env.HOME + "/development/egpu-lab/app/data/modules.js", "utf8");
const data = JSON.parse(src.slice(src.indexOf("{"), src.lastIndexOf("}") + 1));
const w11 = data.modules.find((m) => m.id === "w11");
const typed = w11.cells.filter((c) => c.kind !== "numbers").map((c) => c.lines.filter((l) => !l.trim().startsWith("#")).join("\n")).join("\n");
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(base + "#/m/w06/learn");
await page.waitForSelector(".cell.active");
await page.click('.cell[data-cell="3"] [data-act=focus]');
await page.keyboard.press("Space"); await page.keyboard.press("Space"); await page.keyboard.press("Space");
await page.keyboard.press("b");
await page.waitForTimeout(300);
await page.locator(".cell.active").screenshot({ path: `${out}/10-bulb-long.png` });
await page.click('.cell.active [data-act=ask]');
await page.waitForTimeout(200);
console.log("active", await page.evaluate(() => document.activeElement.tagName + " " + document.querySelector(".cell.active .cell-title").textContent));
await page.keyboard.type("why dtype int32 and not default?");
await page.keyboard.press("Enter");
await page.waitForSelector(".cell.active .answer .nav", { timeout: 40000 });
await page.locator(".cell.active").screenshot({ path: `${out}/11-ask.png` });
await page.goto(base + "#/m/w11/test");
await page.waitForSelector(".cell.active");
await page.click('[data-act=twhole][data-v="1"]');
await page.waitForSelector("textarea[data-ed=whole]");
await page.fill("textarea[data-ed=whole]", typed);
await page.dispatchEvent("textarea[data-ed=whole]", "input");
await page.click("[data-act=wcheck]");
await page.waitForTimeout(200);
await page.click("[data-act=wsyntax]");
await page.waitForTimeout(1500);
await page.click("[data-act=wrun]");
await page.waitForFunction(() => document.querySelector(".console") && !document.querySelector(".console").textContent.includes("Running..."), null, { timeout: 30000 });
await page.screenshot({ path: `${out}/12-whole.png`, fullPage: true });
await page.goto(base + "#/m/w05/practice");
await page.waitForSelector(".cell.active");
await page.click('.cell[data-cell="3"] [data-act=focus]');
await page.click('[data-act=plevel][data-v="3"]');
await page.waitForTimeout(200);
for (let k = 0; k < 5; k++) { const c = await page.$('.cell.active .tray button:not(.used)'); if (c) await c.click(); }
await page.locator(".cell.active").screenshot({ path: `${out}/13-cpp-whole.png` });
await page.click('[data-act=theme]');
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(base + "#/m/w02/learn");
await page.waitForSelector(".cell.active");
await page.keyboard.press("b");
await page.keyboard.press("Space");
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/14-mobile-dark.png` });
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
await page.goto(base);
await page.screenshot({ path: `${out}/15-mobile-home.png` });
console.log("errors:", JSON.stringify(errors), "hscroll:", overflow);
await browser.close();
