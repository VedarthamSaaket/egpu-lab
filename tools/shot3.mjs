import { createRequire } from "module";
const require = createRequire(process.env.HOME + "/development/pixel-arcade/tools/package.json");
const { chromium } = require("playwright");
const out = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("http://localhost:8791/app/");
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForSelector(".card");
await page.screenshot({ path: `${out}/20-home.png` });
await page.click('[data-id="w08"]');
await page.waitForSelector(".cell.active");
await page.waitForTimeout(300);
await page.keyboard.press("Space");
await page.keyboard.press("b");
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/21-module.png` });
await page.click('.toc[data-i="2"]');
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/22-toc.png` });
await page.setViewportSize({ width: 1100, height: 700 });
await page.click('[data-act=mode][data-m=practice]');
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/23-practice-1100.png` });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto("http://localhost:8791/app/");
await page.waitForSelector(".card");
const hs = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
await page.screenshot({ path: `${out}/24-home-mobile.png` });
await page.click('[data-id="w01"]');
await page.waitForTimeout(300);
const hs2 = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
await page.screenshot({ path: `${out}/25-module-mobile.png` });
console.log("errors", JSON.stringify(errors), "hscroll", hs, hs2);
await browser.close();
